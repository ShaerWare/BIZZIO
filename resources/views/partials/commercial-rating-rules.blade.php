     Подключается в блок параметров процедуры (Rfq — этап 1, Auction — этап 2):
     оба хранят одни и те же поля весов. Параметр: $procedure. --}}
@php
    $ratingWeight = fn ($v) => rtrim(rtrim(number_format((float) $v, 2, ',', ''), '0'), ',');
@endphp


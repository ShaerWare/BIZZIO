        <p>
            Рейтинг предложения считается автоматически по трём критериям: цена, срок и аванс.
            Чем меньше значение критерия, тем выгоднее предложение. Каждый критерий приносит
            не больше баллов, чем его вес: цена — {{ $ratingWeight($procedure->weight_price) }},
            срок — {{ $ratingWeight($procedure->weight_deadline) }},
            аванс — {{ $ratingWeight($procedure->weight_advance) }} (сумма весов — 100).
        </p>
        <p>
